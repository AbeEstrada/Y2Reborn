#!/usr/bin/env python3
"""Regenerate crates/reborn-core/src/countries.rs: every country of the tz
database with its zones, for the country-first time zone picker.

    python3 tools/clock/countries.py [/usr/share/zoneinfo] > crates/reborn-core/src/countries.rs

Countries come from iso3166.tab, their zones from zone.tab (one country per
line, unlike zone1970.tab). Only zones that crates/reborn-core/src/zones.rs
has are listed, so the two tables always agree; a country left without a zone
is left out.
"""
import os
import re
import sys

root = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo"
here = os.path.dirname(os.path.abspath(__file__))
zones_rs = os.path.join(here, "..", "..", "crates", "reborn-core", "src", "zones.rs")
with open(zones_rs, encoding="utf-8") as f:
    known = set(re.findall(r'^\s+\("([^"]+)", ', f.read(), re.M))


def table(name):
    with open(os.path.join(root, name), encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            yield line.rstrip("\n").split("\t")


names = {code: name for code, name, *_ in table("iso3166.tab")}
zones = {}
for code, _coordinates, zone, *_ in table("zone.tab"):
    if zone in known:
        zones.setdefault(code, []).append(zone)

print("//! Generated by tools/clock/countries.py from the tz database's iso3166.tab")
print("//! and zone.tab, limited to the zones of zones.rs; do not edit.")
print("//! Each country (ISO 3166 code, English name) with its zones.")
print()
print("#[rustfmt::skip]")
print("pub const COUNTRIES: &[(&str, &str, &[&str])] = &[")
for code, name in sorted(names.items(), key=lambda item: item[1]):
    if code in zones:
        listed = ", ".join(f'"{zone}"' for zone in zones[code])
        escaped = name.replace("\\", "\\\\").replace('"', '\\"')
        print(f'    ("{code}", "{escaped}", &[{listed}]),')
print("];")
