#!/usr/bin/env python3
"""Regenerate crates/reborn-core/src/zones.rs: every tz database zone with
its POSIX TZ rule (the footer line of its TZif file), so the player can
show local time without shipping /usr/share/zoneinfo.

    python3 tools/clock/zones.py [/usr/share/zoneinfo] > crates/reborn-core/src/zones.rs

Zones are the ones listed in zone1970.tab and zone.tab, plus UTC. The output
names the tz release it was made from (tzdata.zi's version line).
"""
import os
import sys

root = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo"
version = "unknown"
zi = os.path.join(root, "tzdata.zi")
if os.path.exists(zi):
    with open(zi, encoding="utf-8") as f:
        first = f.readline().strip()
    if first.startswith("# version "):
        version = first[len("# version ") :]

names = set()
for tab in ("zone1970.tab", "zone.tab"):
    path = os.path.join(root, tab)
    if not os.path.exists(path):
        continue
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            names.add(line.split("\t")[2].strip())
names.add("UTC")

rows = []
for name in sorted(names):
    with open(os.path.join(root, name), "rb") as f:
        data = f.read()
    if not data.startswith(b"TZif"):
        continue
    footer = data.rstrip(b"\n").rsplit(b"\n", 1)[-1].decode("ascii")
    if not footer:
        continue
    rows.append((name, footer))

print(f"//! Generated by tools/clock/zones.py from tz database {version}; do not edit.")
print("//! Each zone with its POSIX TZ rule.")
print()
print("#[rustfmt::skip]")
print("pub const ZONES: &[(&str, &str)] = &[")
for name, rule in rows:
    print(f'    ("{name}", "{rule}"),')
print("];")
